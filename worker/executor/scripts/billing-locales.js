export function resolveBillingCountry(lang, country) {
  const cc = String(country || "").trim().toUpperCase();
  if (cc && PROFILES[cc]) return cc;
  const l = String(lang || "").trim().toLowerCase();
  if (LANG_TO_COUNTRY[l]) return LANG_TO_COUNTRY[l];
  const short = l.split("-")[0];
  if (LANG_TO_COUNTRY[short]) return LANG_TO_COUNTRY[short];
  return "US";
}

// Az adott IP-hez / nyelvhez illő számlázási teszt-adatcsomag.
export function billingProfile(lang, country) {
  const cc = resolveBillingCountry(lang, country);
  return { ...PROFILES[cc], fallback: "Test" };
}
